#!/usr/bin/env python3
"""Generate factorial_table.hpp: (1024 k)! mod 998244353 for k <= 1024, the starting points of
the factorials in factorials.hpp (n! for n < 1025 * 1024). A constexpr table computed by the
compiler instead costs ~2 s of compile time per program (lib/poly/notes.md, Factorials).

Usage: gen_factorials.py [--check]   (--check: exit 1 if factorial_table.hpp differs from the output)
"""
import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent / 'factorial_table.hpp'
P = 998244353
STEP = 1024
COUNT = 1025


def generate() -> str:
    values, f = [], 1
    for k in range(COUNT):
        values.append(f)
        for i in range(STEP * k + 1, STEP * (k + 1) + 1):
            f = f * i % P
    rows = ',\n    '.join(', '.join(str(v) for v in values[i:i + 8]) for i in range(0, COUNT, 8))
    return f'''// Generated by gen_factorials.py. Do not edit.
// (1024 k)! mod 998244353 for k <= 1024.
#pragma once

#include <cstdint>

namespace poly::detail {{

inline constexpr std::uint32_t kFactorialStep = {STEP};
inline constexpr std::uint32_t kFactorialTable[{COUNT}] = {{
    {rows}}};

}}  // namespace poly::detail
'''


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate()
    if args.check:
        if OUT.read_text() != text:
            print(f'{OUT} is stale: run {Path(__file__).name}')
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
